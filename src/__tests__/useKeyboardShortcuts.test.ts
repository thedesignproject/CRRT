import { act, renderHook } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { shortcutPreferenceKey, useKeyboardShortcuts } from '../lib/useKeyboardShortcuts'
const data = new Map<string, string>()
beforeEach(() => {
  data.clear()
  vi.stubGlobal('localStorage', { getItem: (key: string) => data.get(key) ?? null, setItem: (key: string, value: string) => data.set(key, value) })
})
afterEach(() => vi.unstubAllGlobals())
it('shares changes across widget instances, persists reloads, and isolates the dashboard', () => {
  const first = renderHook(() => useKeyboardShortcuts('widget'))
  const second = renderHook(() => useKeyboardShortcuts('widget'))
  const dashboard = renderHook(() => useKeyboardShortcuts('dashboard'))
  expect(first.result.current[0]).toBe(true)
  act(() => first.result.current[1](false))
  expect(second.result.current[0]).toBe(false)
  expect(dashboard.result.current[0]).toBe(true)
  first.unmount()
  const reloaded = renderHook(() => useKeyboardShortcuts('widget'))
  expect(reloaded.result.current[0]).toBe(false)
  act(() => reloaded.result.current[1](true))
  expect(second.result.current[0]).toBe(true)
  expect(data.get(shortcutPreferenceKey('widget'))).toBe('enabled')
})
it('updates on another tab changing the preference or clearing storage', () => {
  const hook = renderHook(() => useKeyboardShortcuts('widget'))
  data.set(shortcutPreferenceKey('widget'), 'disabled')
  act(() => window.dispatchEvent(new StorageEvent('storage', { key: 'unrelated' })))
  expect(hook.result.current[0]).toBe(true)
  act(() => window.dispatchEvent(new StorageEvent('storage', { key: shortcutPreferenceKey('widget') })))
  expect(hook.result.current[0]).toBe(false)
  data.clear()
  act(() => window.dispatchEvent(new StorageEvent('storage', { key: null })))
  expect(hook.result.current[0]).toBe(true)
})
it('works in memory when browser storage is blocked', () => {
  vi.stubGlobal('localStorage', { getItem: () => { throw Error('blocked') }, setItem: () => { throw Error('blocked') } })
  const hook = renderHook(() => useKeyboardShortcuts('widget'))
  expect(hook.result.current[0]).toBe(true)
  act(() => hook.result.current[1](false))
  expect(hook.result.current[0]).toBe(false)
  const lateWidget = renderHook(() => useKeyboardShortcuts('widget'))
  const dashboard = renderHook(() => useKeyboardShortcuts('dashboard'))
  expect(lateWidget.result.current[0]).toBe(false)
  expect(dashboard.result.current[0]).toBe(true)
  hook.unmount()
  lateWidget.unmount()
  const remounted = renderHook(() => useKeyboardShortcuts('widget'))
  expect(remounted.result.current[0]).toBe(false)
  act(() => remounted.result.current[1](true))
  expect(renderHook(() => useKeyboardShortcuts('widget')).result.current[0]).toBe(true)
  vi.stubGlobal('localStorage', { setItem: vi.fn() })
  act(() => remounted.result.current[1](true))
})

it('retains a dashboard opt-out across Inbox mounts when storage writes fail', () => {
  vi.stubGlobal('localStorage', { getItem: () => null, setItem: () => { throw Error('quota') } })
  const app = renderHook(() => useKeyboardShortcuts('dashboard'))
  act(() => app.result.current[1](false))
  const inbox = renderHook(() => useKeyboardShortcuts('dashboard'))
  expect(inbox.result.current[0]).toBe(false)
  expect(renderHook(() => useKeyboardShortcuts('widget')).result.current[0]).toBe(true)
  act(() => window.dispatchEvent(new StorageEvent('storage', { key: 'unrelated' })))
  expect(app.result.current[0]).toBe(false)
  act(() => window.dispatchEvent(new StorageEvent('storage', { key: shortcutPreferenceKey('dashboard') })))
  expect(app.result.current[0]).toBe(true)
  expect(inbox.result.current[0]).toBe(true)
  expect(renderHook(() => useKeyboardShortcuts('dashboard')).result.current[0]).toBe(true)
})
