import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { McpSetup } from './McpSetup'
afterEach(() => vi.restoreAllMocks())
it('guides Codex setup with the actual API endpoint, authorization and a first prompt', async () => {
  const write = vi.fn().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: write } })
  render(<McpSetup apiBase="http://127.0.0.1:3001/api/" />)
  expect(screen.getByRole('button', { name: 'Codex CLI' })).toHaveAttribute('aria-pressed', 'true')
  expect(screen.getByText(/codex mcp add crrt/)).toHaveTextContent("codex mcp add crrt --url 'http://127.0.0.1:3001/api/mcp/v1'")
  for (const name of ['Codex command', 'server URL', 'example prompt']) {
    fireEvent.click(screen.getByRole('button', { name: `Copy ${name}` }))
    await waitFor(() => expect(write).toHaveBeenCalledTimes(['Codex command', 'server URL', 'example prompt'].indexOf(name) + 1))
  }
  expect(write.mock.calls[1][0]).toBe('http://127.0.0.1:3001/api/mcp/v1')
  expect(write.mock.calls[2][0]).toContain('Ready for Agent')
  expect(screen.getByText(/Sign in with your CRRT account/)).toBeInTheDocument()
  expect(screen.getByRole('heading', { name: '2. Review and approve permissions' })).toBeInTheDocument()
  expect(screen.getByText(/explicit request and current project permissions/)).toBeInTheDocument()
  expect(await screen.findAllByText('Copied')).toHaveLength(3)
})
it('explains other clients and handles copy failure without losing selectable setup text', async () => {
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: vi.fn().mockRejectedValue(new Error('denied')) } })
  render(<McpSetup apiBase="/api" />)
  fireEvent.click(screen.getByRole('button', { name: 'Others' }))
  expect(screen.getByText(/Streamable HTTP and OAuth/)).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Copy Codex command' })).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Copy server URL' }))
  expect(await screen.findByRole('status')).toHaveTextContent('Select and copy the text above')
  expect(screen.getByText(new URL('/api/mcp/v1', window.location.origin).href)).toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', { name: 'Codex CLI' }))
  expect(screen.getByRole('button', { name: 'Copy Codex command' })).toBeInTheDocument()
})

it('orders clients and gives Claude Code its own command, authentication, and copy state', async () => {
  const write = vi.fn().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: write } })
  render(<McpSetup apiBase="http://127.0.0.1:3001/api" />)
  expect(within(screen.getByRole('group', { name: 'Choose your MCP client' })).getAllByRole('button').map(button => button.textContent)).toEqual(['Codex CLI', 'Claude Code', 'Others'])
  fireEvent.click(screen.getByRole('button', { name: 'Copy Codex command' }))
  await waitFor(() => expect(screen.getByRole('button', { name: 'Copy Codex command' })).toHaveTextContent('Copied'))
  fireEvent.click(screen.getByRole('button', { name: 'Claude Code' }))
  expect(screen.getByRole('button', { name: 'Claude Code' })).toHaveAttribute('aria-pressed', 'true')
  expect(screen.getByRole('button', { name: 'Copy Claude Code command' })).toHaveTextContent('Copy')
  expect(screen.getByText(/claude mcp add --transport http/)).toHaveTextContent("claude mcp add --transport http crrt 'http://127.0.0.1:3001/api/mcp/v1'")
  expect(screen.getByText('/mcp')).toBeInTheDocument()
  expect(screen.getByText(/and choose Authenticate/)).toBeInTheDocument()
  expect(screen.queryByText('codex mcp login crrt')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Copy Claude Code command' }))
  await waitFor(() => expect(write).toHaveBeenLastCalledWith("claude mcp add --transport http crrt 'http://127.0.0.1:3001/api/mcp/v1'"))
  fireEvent.click(screen.getByRole('button', { name: 'Others' }))
  expect(screen.queryByText('/mcp')).toBeNull()
  expect(screen.queryByText('codex mcp login crrt')).toBeNull()
})
