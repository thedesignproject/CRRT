it('fullscreens the composed player with annotations, camera and camera controls intact', async () => {
  const value = state(); mocks.request.mockResolvedValue({ ...value, recording: { ...value.recording, source: 'window' } })
  const request = vi.fn(async function (this: HTMLElement) {
    Object.defineProperty(document, 'fullscreenElement', { configurable: true, writable: true, value: this })
    document.dispatchEvent(new Event('fullscreenchange'))
  })
  const exit = vi.fn(async () => {
    Object.defineProperty(document, 'fullscreenElement', { configurable: true, writable: true, value: null })
    document.dispatchEvent(new Event('fullscreenchange'))
  })
  Object.defineProperty(HTMLElement.prototype, 'requestFullscreen', { configurable: true, value: request })
  Object.defineProperty(document, 'exitFullscreen', { configurable: true, value: exit })
  render(<RecordingSharePage apiBase="/api" />)
  await screen.findByText('Wikipedia capture')
  const video = document.querySelector('video')!
  Object.defineProperties(video, { videoWidth: { configurable: true, value: 1600 }, videoHeight: { configurable: true, value: 1000 } })
  fireEvent.loadedMetadata(video)
  fireEvent.click(screen.getByRole('button', { name: 'Fullscreen' }))
  await screen.findByRole('button', { name: 'Exit fullscreen' })
  const composition = document.fullscreenElement!
  expect(composition).toHaveClass('recording-composed-player')
  expect(composition).toContainElement(video)
  expect(composition).toContainElement(screen.getByLabelText('Camera'))
  expect(screen.getByLabelText('Camera')).not.toBeVisible()
  expect(screen.getByRole('img', { name: 'Camera preview' })).toBeVisible()
  expect(composition).toContainElement(screen.getByRole('img', { name: 'Recording annotations' }))
  expect(video.parentElement!.style.maxWidth).toContain('1.6')
  expect(video).not.toHaveAttribute('controls')
  expect(composition).toContainElement(screen.getByRole('group', { name: 'Playback controls' }))
  fireEvent.click(screen.getByRole('button', { name: 'Hide camera' }))
  expect(screen.queryByLabelText('Camera')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Show camera' }))
  expect(composition).toContainElement(screen.getByLabelText('Camera'))
  fireEvent.click(screen.getByRole('button', { name: 'Exit fullscreen' }))
  await screen.findByRole('button', { name: 'Fullscreen' })
  expect(exit).toHaveBeenCalledOnce()
  expect(video.parentElement!.style.maxWidth).toContain('65dvh')
  Object.defineProperty(document, 'fullscreenElement', { configurable: true, writable: true, value: document.body })
  fireEvent(document, new Event('fullscreenchange'))
  expect(screen.queryByRole('button', { name: 'Exit fullscreen' })).toBeNull()
})
