it.each(Object.keys(worksheetSpecs) as (keyof typeof worksheetSpecs)[])('edits and exports the %s document without claiming missing data',kind=>{
  render(<ExtendedResourceTools kind={kind}/>)
  const label=worksheetSpecs[kind]!.fields[0][0]
  fireEvent.change(screen.getByLabelText(label),{target:{value:'Accepted target EXAMPLE-21'}})
  expect(output()).toHaveTextContent('Accepted target EXAMPLE-21')
  fireEvent.change(screen.getByLabelText(worksheetSpecs[kind]!.fields[1][0]),{target:{value:''}})
  expect(output()).toHaveTextContent('[Not provided]')
  expect(screen.getByRole('link',{name:'Download output'}).getAttribute('href')).toContain('data:text/markdown')
  fireEvent.change(screen.getByLabelText(label),{target:{value:''}})
  expect(screen.getByRole('button',{name:'Copy result'})).toBeDisabled()
})
it.each(Object.keys(tableSpecs) as (keyof typeof tableSpecs)[])('preserves editable records and exports the %s worksheet',kind=>{
  render(<ExtendedResourceTools kind={kind}/>)
  const spec=tableSpecs[kind]!
  fireEvent.change(screen.getByLabelText(spec.columns[0]),{target:{value:'Original target changed'}})
  expect(output()).toHaveTextContent('Original target changed')
  fireEvent.click(screen.getByRole('button',{name:'Add row'}))
  fireEvent.change(screen.getByLabelText(spec.columns[0]),{target:{value:'Second explicit record'}})
  if(spec.columns.includes('Status')){
    fireEvent.change(screen.getByLabelText('Status'),{target:{value:'Failed'}})
    expect(output()).toHaveTextContent('Failed')
  }
  expect(output()).toHaveTextContent('Second explicit record')
  fireEvent.change(screen.getByLabelText('Row to edit'),{target:{value:'0'}})
  expect(screen.getByLabelText(spec.columns[0])).toHaveValue('Original target changed')
  fireEvent.click(screen.getByRole('button',{name:'Remove row'}))
  expect(output()).not.toHaveTextContent('Original target changed')
})
