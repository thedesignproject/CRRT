it('keeps image files local, validates formats, and produces an escaped annotation',async()=>{
  let reader:any
  class FakeReader { result='data:image/png;base64,AAA'; onload:()=>void=()=>{}; onerror:()=>void=()=>{}; readAsDataURL=vi.fn(()=>this.onload()); constructor(){reader=this} }
  vi.stubGlobal('FileReader',FakeReader)
  const view=render(<ExtendedResourceTools kind="annotator"/>)
  const input=screen.getByLabelText('Local image')
  fireEvent.change(input,{target:{files:[]}})
  fireEvent.change(input,{target:{files:[new File(['text'],'bad.svg',{type:'image/svg+xml'})]}})
  expect(screen.getByText(/Use a PNG/)).toBeInTheDocument()
  await act(async()=>fireEvent.change(input,{target:{files:[new File(['pixel'],'ok.png',{type:'image/png'})]}}))
  fireEvent.change(screen.getByLabelText(/Annotation note/),{target:{value:'<script>example</script>'}})
  screen.getAllByRole('slider').forEach(slider=>fireEvent.change(slider,{target:{value:'25'}}))
  expect(output()).toHaveTextContent('&lt;script&gt;example&lt;/script&gt;')
  expect(screen.getByRole('link',{name:'Download SVG'})).toHaveAttribute('download','crrt-annotation.svg')
  act(()=>reader.onerror())
  expect(screen.getByText(/Could not read/)).toBeInTheDocument()
  view.unmount()
  vi.unstubAllGlobals()
})
