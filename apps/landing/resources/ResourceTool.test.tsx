import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { ResourceTool } from './ResourceTool'

afterEach(() => vi.restoreAllMocks())

it('checks a pair against the chosen text category and handles invalid colors', () => {
  render(<ResourceTool kind="contrast" />)
  fireEvent.change(screen.getByLabelText('Text color'), { target: { value: '#000' } })
  expect(screen.getByLabelText('Contrast result')).toHaveTextContent('21.00:1')
  fireEvent.change(screen.getByLabelText('Text color'), { target: { value: '#777' } })
  expect(screen.getByLabelText('Contrast result')).toHaveTextContent('Does not pass AA normal text')
  fireEvent.change(screen.getByLabelText('Text category'), { target: { value: 'large' } })
  expect(screen.getByLabelText('Contrast result')).toHaveTextContent('Passes AA large text')
  fireEvent.change(screen.getByLabelText('Text category'), { target: { value: 'normal' } })
  fireEvent.change(screen.getByLabelText('Background color'), { target: { value: '#000' } })
  expect(screen.getByLabelText('Contrast result')).toHaveTextContent('Passes AA normal text')
  fireEvent.change(screen.getByLabelText('Text color'), { target: { value: '#zz' } })
  expect(screen.getByLabelText('Text color')).toHaveAttribute('aria-invalid', 'true')
  expect(screen.getByRole('button', { name: 'Copy result' })).toBeDisabled()
  expect(screen.getByText(/Enter valid opaque HEX/)).toBeInTheDocument()
  fireEvent.change(screen.getByLabelText('Text color'), { target: { value: '#fff' } })
  fireEvent.change(screen.getByLabelText('Background color'), { target: { value: '' } })
  expect(screen.getByLabelText('Background color')).toHaveAttribute('aria-invalid', 'true')
})

it('converts units, changes direction, and refuses invalid roots and empty values', () => {
  render(<ResourceTool kind="units" />)
  expect(screen.getByLabelText('Conversion result')).toHaveTextContent('1.5rem')
  fireEvent.change(screen.getByLabelText('Direction'), { target: { value: 'rem-to-px' } })
  fireEvent.change(screen.getByLabelText('Value (rem)'), { target: { value: '1.5' } })
  fireEvent.change(screen.getByLabelText('Root font size (px)'), { target: { value: '20' } })
  expect(screen.getByLabelText('Conversion result')).toHaveTextContent('30px')
  fireEvent.change(screen.getByLabelText('Root font size (px)'), { target: { value: '0' } })
  expect(screen.getByText(/root size greater than zero/)).toBeInTheDocument()
  fireEvent.change(screen.getByLabelText('Root font size (px)'), { target: { value: '' } })
  expect(screen.getByRole('button', { name: 'Copy result' })).toBeDisabled()
  fireEvent.change(screen.getByLabelText('Root font size (px)'), { target: { value: '16' } })
  fireEvent.change(screen.getByLabelText('Value (rem)'), { target: { value: '' } })
  expect(screen.queryByLabelText('Conversion result')).not.toBeInTheDocument()
})

it('edits a feedback brief, handles missing context, and copies the reviewed draft', async () => {
  const writeText = vi.fn().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  render(<ResourceTool kind="feedback" />)
  expect(screen.getByLabelText('Generated feedback brief')).toHaveTextContent('390px')
  fireEvent.change(screen.getByLabelText('Target and context'), { target: { value: '' } })
  expect(screen.getByRole('button', { name: 'Copy brief' })).toBeDisabled()
  fireEvent.change(screen.getByLabelText('Target and context'), { target: { value: '/account · phone' } })
  fireEvent.change(screen.getByLabelText('Observed problem'), { target: { value: 'Save is clipped' } })
  fireEvent.change(screen.getByLabelText('Expected outcome'), { target: { value: 'Save is reachable' } })
  fireEvent.change(screen.getByLabelText('Preserve and reuse (optional)'), { target: { value: '' } })
  fireEvent.change(screen.getByLabelText('Verification steps'), { target: { value: 'Complete a save' } })
  await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Copy brief' })))
  expect(writeText).toHaveBeenCalledWith(expect.stringContaining('## Target\n/account · phone'))
  expect(writeText).toHaveBeenCalledWith(expect.stringContaining('Complete a save'))
  expect(screen.getByRole('button', { name: 'Copied' })).toBeInTheDocument()
})

it('resets copy feedback when the result changes and reports clipboard failures', async () => {
  const writeText = vi.fn().mockResolvedValue(undefined)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  render(<ResourceTool kind="units" />)
  await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Copy result' })))
  expect(writeText).toHaveBeenCalledWith('1.5rem')
  fireEvent.change(screen.getByLabelText('Value (px)'), { target: { value: '32' } })
  expect(screen.getByRole('button', { name: 'Copy result' })).toBeInTheDocument()
  writeText.mockRejectedValueOnce(new Error('Denied'))
  await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Copy result' })))
  expect(screen.getByText(/Couldn’t copy/)).toBeInTheDocument()
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined })
  await act(async () => fireEvent.click(screen.getByRole('button', { name: 'Copy result' })))
  expect(screen.getByText(/Couldn’t copy/)).toBeInTheDocument()
})
