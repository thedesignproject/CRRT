  render(<><h1>Capture target</h1><LandingFeedbackDemo apiBase="/api" projectId="demo" demoComments={demo} /></>)
  fireEvent.keyDown(window, { key: 'c' })
  const heading = screen.getByRole('heading', { name: 'Capture target' })
  const range = document.createRange(); range.selectNodeContents(heading)
  window.getSelection()!.removeAllRanges(); window.getSelection()!.addRange(range)
  fireEvent.click(heading)
  const input = await screen.findByPlaceholderText('Leave your comment…')
  fireEvent.change(input, { target: { value: 'A new captured comment' } })
  fireEvent.click(screen.getByRole('button', { name: 'Send' }))
  await waitFor(() => expect(demo.getSnapshot()).toHaveLength(2))
  fireEvent.keyDown(window, { key: 'Escape' }); fireEvent.keyDown(window, { key: 'f' })
